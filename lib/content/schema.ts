// Редактируемый контент витринных страниц. Значения хранятся строками в
// schools.settings.content[pageKey][fieldKey]; списки — по строке на пункт,
// пары — «левое | правое». Значение по умолчанию = текущий текст страницы,
// поэтому до правки в кабинете сайт выглядит как раньше.

export type FieldType = "text" | "multiline" | "list" | "pairs";

export interface Field {
  key: string;
  label: string;
  type: FieldType;
  default: string;
  hint?: string;
}

export interface PageSpec {
  key: string;
  title: string;
  path: string;
  fields: Field[];
}

// --- Парсеры (чистые) --------------------------------------------------------
export function toLines(raw: string | undefined): string[] {
  if (!raw) return [];
  return raw
    .split(/\r?\n/)
    .map((s) => s.trim())
    .filter(Boolean);
}

export function toPairs(
  raw: string | undefined,
  sep = "|",
): [string, string][] {
  return toLines(raw).map((line) => {
    const i = line.indexOf(sep);
    if (i === -1) return [line.trim(), ""];
    return [line.slice(0, i).trim(), line.slice(i + 1).trim()];
  });
}

