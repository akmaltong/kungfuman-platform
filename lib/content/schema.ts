export function getPage(key: string): PageSpec | undefined {
  return PAGES.find((p) => p.key === key);
}

/** Значения по умолчанию страницы как плоская карта key→строка. */
export function defaultsFor(key: string): Record<string, string> {
  const page = getPage(key);
  if (!page) return {};
  return Object.fromEntries(page.fields.map((f) => [f.key, f.default]));
}
